"""Generate sql/sample_data.sql with fake customers, products and orders."""

import json
import random

from faker import Faker

NUM_CUSTOMERS = 5_000
NUM_PRODUCTS = 50_000
NUM_ORDERS = 50_000
BATCH_SIZE = 1_000

PRODUCT_TYPES = ["T-Shirt", "Hoodie", "Sneakers", "Jacket", "Backpack", "Cap", "Mug", "Watch"]
SIZES = ["XS", "S", "M", "L", "XL"]
COLORS = ["black", "white", "red", "blue", "green", "grey", "yellow"]

fake = Faker()
Faker.seed(42)
random.seed(42)


def quote(value):
    """Return a value as an SQL string literal, escaping single quotes."""
    return "'" + str(value).replace("'", "''") + "'"


def write_inserts(file, table, columns, rows):
    for start in range(0, len(rows), BATCH_SIZE):
        batch = rows[start:start + BATCH_SIZE]
        file.write(f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n")
        file.write(",\n".join("(" + ", ".join(row) + ")" for row in batch))
        file.write(";\n\n")


def main():
    customers = [
        (str(customer_id), quote(fake.first_name()), quote(fake.last_name()), quote(fake.unique.email()))
        for customer_id in range(1, NUM_CUSTOMERS + 1)
    ]

    prices = {}
    products = []
    for product_id in range(1, NUM_PRODUCTS + 1):
        prices[product_id] = round(random.uniform(5, 500), 2)
        metadata = {
            "sizes": sorted(random.sample(SIZES, random.randint(1, len(SIZES))), key=SIZES.index),
            "colors": random.sample(COLORS, random.randint(1, 3)),
        }
        name = f"{fake.word().title()} {random.choice(PRODUCT_TYPES)}"
        products.append((
            str(product_id),
            quote(name),
            str(prices[product_id]),
            str(random.randint(100, 1000)),
            quote(json.dumps(metadata)),
        ))

    orders = []
    order_items = []
    for order_id in range(1, NUM_ORDERS + 1):
        customer_id = random.randint(1, NUM_CUSTOMERS)
        order_date = fake.date_time_between(start_date="-1y")
        orders.append((str(order_id), str(customer_id), quote(order_date)))

        for product_id in random.sample(range(1, NUM_PRODUCTS + 1), random.randint(1, 4)):
            quantity = random.randint(1, 5)
            order_items.append((str(order_id), str(product_id), str(quantity), str(prices[product_id])))

    with open("sql/sample_data.sql", "w", encoding="utf-8") as file:
        file.write("-- Generated by generate_sample_data.py\n\n")
        file.write("TRUNCATE order_items, orders, products, customers RESTART IDENTITY;\n\n")
        write_inserts(file, "customers", ["customer_id", "first_name", "last_name", "email"], customers)
        write_inserts(file, "products", ["product_id", "name", "price", "stock_quantity", "metadata"], products)
        write_inserts(file, "orders", ["order_id", "customer_id", "order_date"], orders)
        write_inserts(file, "order_items", ["order_id", "product_id", "quantity", "unit_price"], order_items)

        # Explicit IDs were inserted, so move each sequence past them for future inserts.
        for table, column in [("customers", "customer_id"), ("products", "product_id"), ("orders", "order_id")]:
            file.write(f"SELECT setval('{table}_{column}_seq', (SELECT MAX({column}) FROM {table}));\n")

    print(f"Wrote {len(customers)} customers, {len(products)} products, "
          f"{len(orders)} orders and {len(order_items)} order items.")


if __name__ == "__main__":
    main()
